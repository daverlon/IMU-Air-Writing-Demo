"""
EMNIST Letters CNN (A–Z), trained on the public EMNIST dataset.

Weights: models/emnist_letters_cnn.pt (generated by train_emnist.py).

The model is trained on pen-on-paper glyphs, but it is fed air-written ones:
slanted, unevenly weighted, with loops that don't quite close. Rather than
trusting a single rendering of a stroke, every stroke is rendered many ways
and the votes are averaged, so no single unlucky rendering decides the answer.

Measured on 53 hand-written letters, the ±15° / three ink weights / two
paddings grid is the best of the ranges tried; widening it past ±15° starts
losing accuracy again, and the strokes need no global rotation or shear.
"""

from __future__ import annotations

import math
import string
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn

from rasterize import path_extent, stroke_to_image

ROOT = Path(__file__).resolve().parent
WEIGHTS = ROOT / "models" / "emnist_letters_cnn.pt"
LETTERS = string.ascii_uppercase
MIN_EXTENT = 0.01  # app gates stroke size; this only rejects degenerate input

TTA_ANGLES = (-15, -8, 0, 8, 15)  # air writing slants differently every time
TTA_INK = (0.7, 1.0, 1.4)  # pen weight relative to EMNIST
TTA_PADDING = (0.12, 0.20)  # how much of the frame the glyph fills

# A glyph with essentially no width cannot be an 'L', 'T' or 'E' — only a bar.
# Without this a hand-drawn 'I' reads as 'L' about as often as not.
# 0.20 was too tight: a real I in "DAVID" came in at aspect 0.31 and lost to L.
NARROW_ASPECT = 0.36
NARROW_LETTERS = "IJ"
NARROW_OK = "TEF"  # a bar plus short arms — do not crush these into I
NARROW_OK_DAMPING = 0.50
NARROW_DAMPING = 0.12
# A bit wider than a bar, still not an H/M/N — the caret-shaped I in "IS".
MID_ASPECT = 0.58
WIDE_LETTERS = "HMNWU"
WIDE_DAMPING = 0.25


class LetterCNN(nn.Module):
    def __init__(self):
        super().__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(1, 32, 3, padding=1),
            nn.ReLU(),
            nn.MaxPool2d(2),
            nn.Conv2d(32, 64, 3, padding=1),
            nn.ReLU(),
            nn.MaxPool2d(2),
        )
        self.fc = nn.Sequential(
            nn.Linear(64 * 7 * 7, 256),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(256, 26),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = self.conv(x)
        return self.fc(x.view(x.size(0), -1))


@dataclass
class Prediction:
    letter: str
    confidence: float
    top3: list[tuple[str, float]]
    preview: np.ndarray  # (28, 28) upright
    probs: np.ndarray | None = None
    raw_letter: str | None = None
    raw_top3: list[tuple[str, float]] | None = None


class LetterClassifier:
    def __init__(self):
        self.device = torch.device("cpu")
        self.model = LetterCNN().to(self.device)
        if not WEIGHTS.exists():
            print("No local weights — run: python train_emnist.py")
            raise FileNotFoundError(WEIGHTS)
        blob = torch.load(WEIGHTS, map_location=self.device, weights_only=False)
        self.model.load_state_dict(blob["state_dict"])
        self.model.eval()
        print(f"Letter model ready ({WEIGHTS.name}, EMNIST A–Z upright)")

    @torch.inference_mode()
    def predict_image(self, upright: np.ndarray) -> Prediction:
        """upright: (1, 28, 28) natural orientation (matches training)."""
        tensor = torch.from_numpy(upright).unsqueeze(0).to(self.device)
        probs = torch.softmax(self.model(tensor), dim=1)[0].cpu().numpy()
        order = np.argsort(-probs)
        top3 = [(LETTERS[i], float(probs[i])) for i in order[:3]]
        return Prediction(
            letter=top3[0][0],
            confidence=top3[0][1],
            top3=top3,
            preview=upright[0].copy(),
            probs=probs,
        )

    def predict_stroke(self, points: list[tuple[float, float, int]]) -> Prediction | None:
        if len(points) < 10:
            return None
        if path_extent(points) < MIN_EXTENT:
            return None
        preview = stroke_to_image(points)
        if float(preview.max()) < 0.05:
            return None

        probs = self._augmented_probs(points)
        probs = self._apply_shape_prior(points, probs)
        order = np.argsort(-probs)
        top3 = [(LETTERS[i], float(probs[i])) for i in order[:3]]
        return Prediction(
            letter=top3[0][0],
            confidence=top3[0][1],
            top3=top3,
            preview=preview[0].copy(),
            probs=probs,
        )

    @torch.inference_mode()
    def _augmented_probs(self, points) -> np.ndarray:
        """Render the stroke many ways; keep the best evidence across views."""
        views = []
        for angle in TTA_ANGLES:
            rotated = _rotate(points, angle)
            for ink in TTA_INK:
                for padding in TTA_PADDING:
                    views.append(stroke_to_image(rotated, padding=padding, ink=ink))
        batch = torch.from_numpy(np.stack(views)).to(self.device)
        probs = torch.softmax(self.model(batch), dim=1).cpu().numpy()
        # Averaging, not max: taking the best view means taking the most extreme
        # one, and a wrong view that happens to be confident then wins outright.
        # Over 53 hand-written letters this was worth 4 points of accuracy.
        pooled = probs.mean(axis=0)
        return pooled / max(pooled.sum(), 1e-9)

    @staticmethod
    def _apply_shape_prior(points, probs: np.ndarray) -> np.ndarray:
        xs = [p[0] for p in points]
        ys = [p[1] for p in points]
        width, height = max(xs) - min(xs), max(ys) - min(ys)
        if height <= 1e-9:
            return probs
        aspect = width / height
        if aspect < NARROW_ASPECT:
            mask = np.array(
                [
                    1.0
                    if L in NARROW_LETTERS
                    else NARROW_OK_DAMPING
                    if L in NARROW_OK
                    else NARROW_DAMPING
                    for L in LETTERS
                ]
            )
        elif aspect < MID_ASPECT:
            mask = np.array(
                [WIDE_DAMPING if L in WIDE_LETTERS else 1.0 for L in LETTERS]
            )
        else:
            return probs
        damped = probs * mask
        return damped / max(damped.sum(), 1e-9)


def _rotate(points, degrees: float):
    if degrees == 0:
        return points
    r = math.radians(degrees)
    cos, sin = math.cos(r), math.sin(r)
    return [(x * cos - y * sin, x * sin + y * cos, t) for x, y, t in points]
